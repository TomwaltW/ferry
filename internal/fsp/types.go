// Package fsp defines the frozen protocol types shared by every Ferry
// component: IM endpoints, inbound and outbound messages, sessions, agent
// events and approvals. Nothing in this package depends on a concrete IM
// platform or agent driver.
package fsp

import "time"

type Platform string

const (
	PlatformWeChat Platform = "wechat"
	PlatformFeishu Platform = "feishu"
	PlatformFake   Platform = "fake"
)

// EndpointID uniquely identifies an IM conversation: platform plus bot account
// plus peer (the other user's ID in a direct chat).
type EndpointID struct {
	Platform Platform
	BotID    string
	PeerID   string
}

type Lang string

const (
	LangZH Lang = "zh-CN"
	LangEN Lang = "en"
)

type Attachment struct {
	Kind     string // image | file | voice | video
	Name     string
	MIMEType string
	Path     string // absolute path once downloaded and decrypted; empty otherwise
	Size     int64
}

type Inbound struct {
	Endpoint    EndpointID
	SenderID    string
	MessageID   string
	Text        string
	Attachments []Attachment
	ReplyCtx    string // platform reply context (context_token on WeChat); opaque to the core
	ReceivedAt  time.Time
}

type OutKind string

const (
	OutText     OutKind = "text"
	OutFile     OutKind = "file"
	OutApproval OutKind = "approval"
)

type Outbound struct {
	Endpoint  EndpointID
	Session   SessionID // empty for system messages
	Kind      OutKind
	Text      string
	FilePath  string
	DedupeKey string // stable across retries; maps to client_id on WeChat; generated by the outbox when empty
	Urgent    bool   // approval requests and the final result of a turn
}

type DeliveryState string

const (
	DeliveryQueued   DeliveryState = "queued"
	DeliverySending  DeliveryState = "sending"
	DeliveryAccepted DeliveryState = "accepted"
	DeliveryUnknown  DeliveryState = "unknown"
	DeliveryRejected DeliveryState = "rejected"
	DeliveryHeld     DeliveryState = "held"
)

type (
	SessionID     string
	SessionOrigin string
	SessionState  string
	DriverKind    string
)

const (
	OriginManaged  SessionOrigin = "managed"
	OriginTerminal SessionOrigin = "terminal"

	StateStarting SessionState = "starting"
	StateIdle     SessionState = "idle"
	StateRunning  SessionState = "running"
	StateAwaiting SessionState = "awaiting"
	StateParked   SessionState = "parked"
	StateClosed   SessionState = "closed"

	DriverACP           DriverKind = "acp"
	DriverServer        DriverKind = "server"
	DriverProxy         DriverKind = "proxy"
	DriverClaudeChannel DriverKind = "claude-channel"
	DriverPTY           DriverKind = "pty"
)

type Session struct {
	ID             SessionID
	Driver         DriverKind
	Agent          string // agent name from the configuration
	Cwd            string // absolute path
	AgentSessionID string
	Origin         SessionOrigin
	State          SessionState
	Owner          EndpointID
	CreatedAt      time.Time
	LastActive     time.Time
}

type EventKind string

const (
	EvChunk    EventKind = "agent.chunk"
	EvThought  EventKind = "agent.thought"
	EvTool     EventKind = "agent.tool"
	EvPlan     EventKind = "agent.plan"
	EvApproval EventKind = "agent.approval"
	EvTurnEnd  EventKind = "agent.turn_end"
	EvError    EventKind = "agent.error"
)

type ToolInfo struct{ CallID, Kind, Title, Status string }

type PlanStep struct{ Title, Status string }

type Event struct {
	Session    SessionID
	Kind       EventKind
	Text       string
	Tool       *ToolInfo
	Plan       []PlanStep
	Approval   *ApprovalRequest
	StopReason string // EvTurnEnd: end_turn | cancelled | max_tokens | refusal | error
	Err        string
	At         time.Time
}

type ApprovalOptionKind string

const (
	OptAllowOnce    ApprovalOptionKind = "allow_once"
	OptAllowAlways  ApprovalOptionKind = "allow_always"
	OptRejectOnce   ApprovalOptionKind = "reject_once"
	OptRejectAlways ApprovalOptionKind = "reject_always"
)

type ApprovalOption struct {
	ID    string
	Kind  ApprovalOptionKind
	Label string
}

type ApprovalRequest struct {
	ID           string // 5 characters from abcdefghijkmnopqrstuvwxyz; assigned by the approval module
	Session      SessionID
	ToolName     string
	ToolKind     string // read edit delete move search execute think fetch switch_mode other
	Description  string
	InputPreview string // at most 2000 characters
	Paths        []string
	Options      []ApprovalOption
	CreatedAt    time.Time
}

type Decision string

const (
	DecisionAllowOnce   Decision = "allow_once"
	DecisionAllowAlways Decision = "allow_always"
	DecisionReject      Decision = "reject"
)

type Verdict struct {
	ApprovalID string
	Decision   Decision
	OptionID   string // the agent's option ID; empty means cancelled
	By         string // sender ID of the decider, or policy / timeout / cancel
}
