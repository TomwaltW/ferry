// downloadTimeout caps a single archive download. Agent archives run to tens of
// megabytes, so it is generous rather than snappy.
const downloadTimeout = 10 * time.Minute

// launchKind is how a resolved agent is started.
type launchKind string

const (
	launchCommand  launchKind = "command"  // a command spelled out in the configuration
	launchPath     launchKind = "path"     // the registry's binary, already on PATH
	launchNPX      launchKind = "npx"      // npx -y <package>
	launchUVX      launchKind = "uvx"      // uvx <package>
	launchDownload launchKind = "download" // fetch and unpack the registry's archive
)

// Reasons reported through ports.AgentInfo. They are plain English because the
// registry has no access to the i18n catalogue; the core renders them into the
// agents.available and agents.unavailable templates.
const (
	reasonDownload  = "downloaded on first use"
	reasonNoNPX     = "npx not found, install Node.js"
	reasonNoUVX     = "uvx not found, install uv"
	reasonNoCommand = "no command configured"
)

// launch is the decision made for one agent: how to start it and with what.
// For launchDownload the command is only known once the archive is unpacked, so
// binary carries what is needed to do that.
type launch struct {
	kind   launchKind
	cmd    []string
	env    []map[string]string
	binary binaryDist
	entry  entry
	// note explains the choice to the user when the agent is listed; empty
	// means there is nothing worth saying.
	note string
}

// resolver turns configured agent names into launch specs. It reads the
// committed snapshot only: refreshing the snapshot is a manual step run through
// internal/registry/cmd/snapshot.
type resolver struct {
	cfg      config.RegistryConfig
	agents   []config.AgentConfig
	byName   map[string]config.AgentConfig
	snapshot map[string]entry
	home     string
	log      *slog.Logger
	client   *http.Client
}

var _ ports.Registry = (*resolver)(nil)

// New resolves configured agents into launch specs, using the committed
// registry snapshot for agents referenced by registry name.
func New(cfg config.RegistryConfig, agents []config.AgentConfig, home string, log *slog.Logger) (ports.Registry, error) {
	snapshot, err := parseSnapshot(snapshotJSON)
	if err != nil {
		return nil, err
	}
	return newWithSnapshot(cfg, agents, home, log, snapshot)
}

// newWithSnapshot is New over a snapshot supplied by the caller. Tests use it
// to exercise distributions the committed snapshot happens not to carry.
func newWithSnapshot(cfg config.RegistryConfig, agents []config.AgentConfig, home string, log *slog.Logger, snapshot map[string]entry) (*resolver, error) {
	if log == nil {
		log = slog.New(slog.DiscardHandler)
	}
	if home == "" {
		return nil, fmt.Errorf("registry: home must not be empty")
	}

	byName := make(map[string]config.AgentConfig, len(agents))
	for _, a := range agents {
		if a.Name == "" {
			return nil, fmt.Errorf("registry: an agent has no name")
		}
		if _, dup := byName[a.Name]; dup {
			return nil, fmt.Errorf("registry: agent %q is configured twice", a.Name)
		}
		if (a.Registry == "") == (len(a.Command) == 0) {
			return nil, fmt.Errorf("registry: agent %q must set exactly one of registry and command", a.Name)
		}
		byName[a.Name] = a
	}

	if !cfg.SnapshotOnly {
		// P1 has no online refresh: the snapshot is regenerated by hand.
		log.Debug("registry.snapshot_only is off but P1 only reads the committed snapshot")
	}

	return &resolver{
		cfg:      cfg,
		agents:   slices.Clone(agents),
		byName:   byName,
		snapshot: snapshot,
		home:     home,
		log:      log,
		client:   &http.Client{Timeout: downloadTimeout},
	}, nil
}

// Resolve returns the launch spec for a configured agent. Cwd is left to the
// caller. An agent distributed as a binary that is not on PATH yet is
// downloaded here, which is why Resolve takes a context.
func (r *resolver) Resolve(ctx context.Context, agent string) (ports.SessionSpec, error) {
	ac, ok := r.byName[agent]
	if !ok {
		return ports.SessionSpec{}, fmt.Errorf("registry: agent %q: %w", agent, fsp.ErrNotFound)
	}

	l, err := r.plan(ac)
	if err != nil {
		return ports.SessionSpec{}, err
	}

	cmd := l.cmd
	if l.kind == launchDownload {
		cmd, err = r.download(ctx, l)
		if err != nil {
			return ports.SessionSpec{}, err
		}
	}

	return ports.SessionSpec{
		Agent:   agent,
		Command: cmd,
		Env:     buildEnv(l.env...),
	}, nil
}

// Agents reports every configured agent and whether it can be started. An
// agent that still needs downloading counts as available, with a note saying so.
func (r *resolver) Agents(ctx context.Context) []ports.AgentInfo {
	out := make([]ports.AgentInfo, 0, len(r.agents))
	for _, ac := range r.agents {
		info := ports.AgentInfo{Name: ac.Name, Display: ac.Name, Source: "command"}
		if ac.Registry != "" {
			info.Source = "registry"
			if e, ok := r.snapshot[ac.Registry]; ok && e.Name != "" {
				info.Display = e.Name
			}
		}

		l, err := r.plan(ac)
		switch {
		case err != nil:
			info.Available = false
			info.Reason = reasonOf(err)
		default:
			info.Available = true
			info.Reason = l.note
		}
		out = append(out, info)
	}
	return out
}

// reasonOf strips the package prefix off a planning error so the text reads as
// a reason rather than as a Go error.
func reasonOf(err error) string {
	return strings.TrimPrefix(err.Error(), "registry: ")
}

// plan decides how one configured agent is started, without doing any work that
// touches the network. Agents calls it to report availability and Resolve calls
// it before downloading anything.
func (r *resolver) plan(ac config.AgentConfig) (launch, error) {
	if len(ac.Command) > 0 {
		return r.planCommand(ac)
	}

	e, ok := r.snapshot[ac.Registry]
	if !ok {
		return launch{}, fmt.Errorf("registry: no registry agent named %q: %w", ac.Registry, fsp.ErrNotFound)
	}
	return r.planRegistry(ac, e)
}

// planCommand checks a command spelled out in the configuration. A bare name is
// looked up on PATH, anything else has to exist as an executable file.
func (r *resolver) planCommand(ac config.AgentConfig) (launch, error) {
	exe := ac.Command[0]
	if exe == "" {
		return launch{}, fmt.Errorf("registry: %s", reasonNoCommand)
	}

	resolved, err := exec.LookPath(exe)
	if err != nil {
		return launch{}, fmt.Errorf("registry: %s not found", exe)
	}

	cmd := append([]string{resolved}, ac.Command[1:]...)
	return launch{kind: launchCommand, cmd: cmd, env: []map[string]string{ac.Env}}, nil
}

// planRegistry applies the order of preference from spec-p1 3.8: a binary
// already on PATH, then npx, then uvx, then downloading the binary.
func (r *resolver) planRegistry(ac config.AgentConfig, e entry) (launch, error) {
	d := e.Distribution
	bin, hasBinary := d.Binary[platformKey()]

	if hasBinary {
		if found, err := exec.LookPath(binaryName(bin.Cmd)); err == nil {
			return launch{
				kind:  launchPath,
				cmd:   append([]string{found}, bin.Args...),
				env:   []map[string]string{e.Env, bin.Env, ac.Env},
				entry: e,
			}, nil
		}
	}

	var why []string
	if d.NPX != nil {
		if _, err := exec.LookPath("npx"); err == nil {
			env := []map[string]string{e.Env, d.NPX.Env, ac.Env}
			if r.cfg.NPMRegistry != "" {
				env = append(env, map[string]string{"npm_config_registry": r.cfg.NPMRegistry})
			}
			cmd := append([]string{"npx", "-y", d.NPX.Package}, d.NPX.Args...)
			return launch{kind: launchNPX, cmd: cmd, env: env, entry: e}, nil
		}
		why = append(why, reasonNoNPX)
	}

	if d.UVX != nil {
		if _, err := exec.LookPath("uvx"); err == nil {
			cmd := append([]string{"uvx", d.UVX.Package}, d.UVX.Args...)
			return launch{
				kind:  launchUVX,
				cmd:   cmd,
				env:   []map[string]string{e.Env, d.UVX.Env, ac.Env},
				entry: e,
			}, nil
		}
		why = append(why, reasonNoUVX)
	}

	if hasBinary {
		return launch{
			kind:   launchDownload,
			env:    []map[string]string{e.Env, bin.Env, ac.Env},
			binary: bin,
			entry:  e,
			note:   reasonDownload,
		}, nil
	}

	if len(why) == 0 {
		why = append(why, "no build for "+platformKey())
	}
	return launch{}, fmt.Errorf("registry: %s", strings.Join(why, "; "))
}

// binaryName is the file name of a registry cmd such as "./kimi", which is what
// the agent is called if it is already installed on PATH.
func binaryName(cmd string) string {
	return path.Base(path.Clean(strings.TrimPrefix(cmd, "./")))
}

// platformKey is the registry's key for the running platform: the Go OS with an
// arch spelled the way release archives usually spell it.
func platformKey() string {
	arch := runtime.GOARCH
	switch arch {
	case "amd64":
		arch = "x86_64"
	case "arm64":
		arch = "aarch64"
	}
	return runtime.GOOS + "-" + arch
}

// executable reports whether path is a file the current user can run.
func executable(p string) bool {
	info, err := os.Stat(p)
	if err != nil || info.IsDir() {
		return false
	}
	if runtime.GOOS == "windows" {
		return true
	}
	return info.Mode().Perm()&0o111 != 0
}
